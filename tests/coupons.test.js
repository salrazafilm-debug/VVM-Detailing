const assert = require('assert');
const { toCoupon } = require('../server/coupon-db');
const c = toCoupon({ code: 'KIMBEACH160', item: 'Full Factory Reset', label: 'SUV', price_cents: 16000, saving_cents: 16000, uses_limit: 3, customer_name: 'Kim', vehicle: '2021 Chevy Equinox', phone: '4109913607', email: 'kimsmith0506@gmail.com', address: '' });
assert.equal(c.priceCents, 16000);
assert.equal(c.savingCents, 16000);
assert.equal(c.uses, 3);
assert.equal(c.customer, 'Kim');
assert.equal(c.phone, '4109913607');
const bare = toCoupon({ code: 'X1', item: 'Full Factory Reset', label: 'Sedan', price_cents: 10000, saving_cents: 5000, uses_limit: 1 });
assert.equal(bare.customer, ''); assert.equal(bare.email, '');
console.log('coupon tests passed');
